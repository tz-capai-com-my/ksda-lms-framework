import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = new URL('../', import.meta.url);
const quote = value => `'${value.replaceAll("'", "''")}'`;

export function renderCourseSeed(catalogue) {
  if (!Array.isArray(catalogue) || !catalogue.length) throw new Error('Course catalogue must be a nonempty array.');
  const slugs = new Set();
  const rows = catalogue.map((course, index) => {
    const { databaseSlug, title, outcome, missions } = course;
    if (typeof databaseSlug !== 'string' || !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(databaseSlug) || slugs.has(databaseSlug)) {
      throw new Error(`Course ${index + 1}: invalid or duplicate databaseSlug.`);
    }
    slugs.add(databaseSlug);
    if (typeof title !== 'string' || !title.trim() || title.length > 200 || title.includes('\0') ||
        typeof outcome !== 'string' || !outcome.trim() || outcome.length > 2000 || outcome.includes('\0') ||
        !Number.isInteger(missions) || missions < 1 || missions > 128) {
      throw new Error(`Course ${index + 1}: invalid title, outcome or missions.`);
    }
    return `  (${quote(databaseSlug)}, ${quote(title)}, ${quote(outcome)}, 'mission', 'free', 'published', ${index + 1}, ${missions})`;
  });
  return `-- Generated by node scripts/generate-course-seed.mjs from config/course-catalogue.json.\n-- Fresh isolated framework project ONLY; not the existing CAPAi database.\n-- New catalogue entries are published/free. Existing access/status decisions are preserved.\nbegin;\ninsert into public.courses (slug, title, short_description, experience_style, access_type, status, sort_order, mission_count)\nvalues\n${rows.join(',\n')}\non conflict (slug) do update set\n  title = excluded.title,\n  short_description = excluded.short_description,\n  sort_order = excluded.sort_order,\n  mission_count = excluded.mission_count;\ncommit;\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const catalogue = JSON.parse(await readFile(new URL('config/course-catalogue.json', root), 'utf8'));
  await writeFile(new URL('supabase/seed.sql', root), renderCourseSeed(catalogue));
  console.log(`Generated catalogue seed for ${catalogue.length} modules.`);
}
